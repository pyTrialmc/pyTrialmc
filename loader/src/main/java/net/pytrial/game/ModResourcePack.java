package net.pytrial.game;

import com.google.gson.JsonObject;
import net.pytrial.util.PyTrialLog;

import javax.imageio.ImageIO;
import java.awt.Color;
import java.awt.Graphics2D;
import java.awt.image.BufferedImage;
import java.io.IOException;
import java.io.InputStream;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.time.Duration;
import java.util.ArrayList;
import java.util.List;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

/**
 * Resource pack generated from the declared mod content.
 *
 * <p>It writes the block state, the block model and a texture for every declared block, so a mod
 * block has a real appearance without the mod shipping resources of its own. The pack is dropped into
 * {@code <gameDir>/resourcepacks/pytrial_generated} and enabled in options.txt, which means it takes
 * effect from the next start of the game.
 */
public final class ModResourcePack {

    public static final String PACK_ID = "pytrial_generated";
    public static final String PACK_DESCRIPTION = "Block states, models and textures generated by pyTrial";
    public static final int FALLBACK_FORMAT = 34;
    public static final int TEXTURE_SIZE = 16;

    private static final Color TEMPLATE_BASE = new Color(0x3A3A46);
    private static final Color TEMPLATE_ACCENT = new Color(0x8A3FB8);

    private ModResourcePack() {
    }

    public static void install(Path gameDir, List<ContentRegistry.BlockEntry> blocks) {
        if (gameDir == null || blocks == null || blocks.isEmpty()) {
            return;
        }
        try {
            Path packDir = gameDir.resolve("resourcepacks").resolve(PACK_ID);
            Files.createDirectories(packDir);
            writeMeta(packDir, readVanillaFormat(gameDir));

            int written = 0;
            for (ContentRegistry.BlockEntry block : blocks) {
                if (writeBlock(packDir, block)) {
                    written++;
                }
            }
            enable(gameDir);
            PyTrialLog.info("Generated a resource pack for " + written + " block(s): " + packDir);
            PyTrialLog.info("  enable it once (already added to options.txt), textures appear after a restart");
        } catch (Throwable t) {
            PyTrialLog.warn("Cannot generate the resource pack: " + t.getMessage());
        }
    }

    private static boolean writeBlock(Path packDir, ContentRegistry.BlockEntry block) {
        String namespace = block.namespace();
        String path = block.path();
        try {
            Path blockstates = packDir.resolve("assets").resolve(namespace).resolve("blockstates");
            Path models = packDir.resolve("assets").resolve(namespace).resolve("models").resolve("block");
            Path textures = packDir.resolve("assets").resolve(namespace).resolve("textures").resolve("block");
            Files.createDirectories(blockstates);
            Files.createDirectories(models);

            String model = namespace + ":block/" + path;
            String texture = resolveTexture(textures, namespace, path, block.texture());
            write(blockstates.resolve(path + ".json"),
                    "{\n  \"variants\": {\n    \"\": { \"model\": \"" + model + "\" }\n  }\n}\n");
            write(models.resolve(path + ".json"),
                    "{\n  \"parent\": \"minecraft:block/cube_all\",\n"
                            + "  \"textures\": { \"all\": \"" + texture + "\" }\n}\n");
            return true;
        } catch (Throwable t) {
            PyTrialLog.warn("Cannot generate the resources of " + namespace + ":" + path + ": " + t.getMessage());
            return false;
        }
    }

    /**
     * Resolves the texture source of a block.
     *
     * <ul>
     *   <li>{@code namespace:path} (for example {@code minecraft:block/stone}) is referenced as is,
     *       so a vanilla texture needs no file at all;</li>
     *   <li>{@code http(s)://...} is downloaded into the pack and reused on later starts;</li>
     *   <li>anything else is a file path, copied into the pack;</li>
     *   <li>without a source, the generated template is used.</li>
     * </ul>
     */
    private static String resolveTexture(Path textures, String namespace, String path, String source)
            throws IOException, InterruptedException {
        String own = namespace + ":block/" + path;
        if (source == null || source.isBlank()) {
            writeTemplate(textures.resolve(path + ".png"));
            return own;
        }
        if (source.matches("[a-z0-9_.-]+:[a-z0-9_./-]+") && !source.contains("://")) {
            PyTrialLog.info("Block " + namespace + ":" + path + " uses the existing texture " + source);
            return source;
        }

        Path target = textures.resolve(path + ".png");
        if (source.startsWith("http://") || source.startsWith("https://")) {
            if (Files.isRegularFile(target)) {
                return own;
            }
            download(source, target);
            PyTrialLog.info("Downloaded the texture of " + namespace + ":" + path + " from " + source);
            return own;
        }

        Path file = Path.of(source);
        if (Files.isRegularFile(file)) {
            Files.createDirectories(textures);
            Files.copy(file, target, StandardCopyOption.REPLACE_EXISTING);
            PyTrialLog.info("Copied the texture of " + namespace + ":" + path + " from " + file);
            return own;
        }

        PyTrialLog.warn("Texture not found: " + source + ", using the template for " + namespace + ":" + path);
        writeTemplate(target);
        return own;
    }

    private static void download(String url, Path target) throws IOException, InterruptedException {
        Files.createDirectories(target.getParent());
        HttpClient client = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(10)).build();
        HttpRequest request = HttpRequest.newBuilder(URI.create(url))
                .timeout(Duration.ofSeconds(30))
                .GET()
                .build();
        HttpResponse<byte[]> response = client.send(request, HttpResponse.BodyHandlers.ofByteArray());
        if (response.statusCode() != 200) {
            throw new IOException("HTTP " + response.statusCode());
        }
        byte[] body = response.body();
        if (body.length < 8 || (body[0] & 0xFF) != 0x89 || body[1] != 'P') {
            throw new IOException("the response is not a PNG");
        }
        Files.write(target, body);
    }

    /** Draws the placeholder texture a mod gets until it ships its own. */
    private static void writeTemplate(Path target) throws IOException {
        BufferedImage image = new BufferedImage(TEXTURE_SIZE, TEXTURE_SIZE, BufferedImage.TYPE_INT_ARGB);
        Graphics2D graphics = image.createGraphics();
        graphics.setColor(TEMPLATE_BASE);
        graphics.fillRect(0, 0, TEXTURE_SIZE, TEXTURE_SIZE);
        graphics.setColor(TEMPLATE_ACCENT);
        for (int y = 0; y < TEXTURE_SIZE; y += 4) {
            for (int x = 0; x < TEXTURE_SIZE; x += 4) {
                if (((x + y) / 4) % 2 == 0) {
                    graphics.fillRect(x, y, 2, 2);
                }
            }
        }
        graphics.dispose();
        ImageIO.write(image, "png", target.toFile());
    }

    private static void writeMeta(Path packDir, int format) throws IOException {
        write(packDir.resolve("pack.mcmeta"),
                "{\n  \"pack\": {\n    \"pack_format\": " + format + ",\n"
                        + "    \"supported_formats\": { \"min_inclusive\": 1, \"max_inclusive\": 999 },\n"
                        + "    \"description\": \"" + PACK_DESCRIPTION + "\"\n  }\n}\n");
    }

    /**
     * Called from the agent premain: writes the pack skeleton and enables it.
     *
     * <p>Enabling has to happen before the game reads options.txt. Doing it while the game runs is
     * useless, because the game keeps the pack list in memory and overwrites the file on exit.
     */
    public static void ensureBeforeGameStart(Path gameDir) {
        if (gameDir == null || !net.pytrial.ui.PyTrialSettings.generatedResourcePack()) {
            return;
        }
        try {
            Path packDir = gameDir.resolve("resourcepacks").resolve(PACK_ID);
            Files.createDirectories(packDir);
            Path meta = packDir.resolve("pack.mcmeta");
            if (!Files.isRegularFile(meta)) {
                writeMeta(packDir, readVanillaFormat(gameDir));
            }
            enable(gameDir);
        } catch (Throwable t) {
            PyTrialLog.warn("Cannot prepare the resource pack: " + t.getMessage());
        }
    }

    /** Uses the pack format of the installed client so the pack is never flagged as incompatible. */
    private static int readVanillaFormat(Path gameDir) {
        String version = System.getProperty("pytrial.version");
        if (version == null || version.isBlank()) {
            return FALLBACK_FORMAT;
        }
        Path clientJar = gameDir.resolve("versions").resolve(version).resolve(version + ".jar");
        if (!Files.isRegularFile(clientJar)) {
            return FALLBACK_FORMAT;
        }
        try (ZipFile zip = new ZipFile(clientJar.toFile())) {
            ZipEntry entry = zip.getEntry("pack.mcmeta");
            if (entry == null) {
                return FALLBACK_FORMAT;
            }
            try (InputStream input = zip.getInputStream(entry)) {
                JsonObject root = com.google.gson.JsonParser.parseString(
                        new String(input.readAllBytes(), StandardCharsets.UTF_8)).getAsJsonObject();
                JsonObject pack = root.getAsJsonObject("pack");
                if (pack != null && pack.has("pack_format")) {
                    int format = pack.get("pack_format").getAsInt();
                    PyTrialLog.info("Using the pack format of the client: " + format);
                    return format;
                }
            }
        } catch (Throwable t) {
            PyTrialLog.debug("Cannot read the vanilla pack format: " + t.getMessage());
        }
        return FALLBACK_FORMAT;
    }

    /** Adds the pack to the enabled list of options.txt, keeping whatever is already enabled. */
    private static void enable(Path gameDir) throws IOException {
        Path options = gameDir.resolve("options.txt");
        String entry = "\"file/" + PACK_ID + "\"";
        List<String> lines = new ArrayList<>();
        if (Files.isRegularFile(options)) {
            lines.addAll(Files.readAllLines(options, StandardCharsets.UTF_8));
        }

        for (int index = 0; index < lines.size(); index++) {
            String line = lines.get(index);
            if (!line.startsWith("resourcePacks:")) {
                continue;
            }
            if (line.contains(entry)) {
                return;
            }
            int open = line.indexOf('[');
            if (open < 0) {
                return;
            }
            String head = line.substring(0, open + 1);
            String tail = line.substring(open + 1);
            lines.set(index, head + entry + (tail.startsWith("]") ? "" : ",") + tail);
            write(options, String.join(System.lineSeparator(), lines) + System.lineSeparator());
            PyTrialLog.info("Enabled the generated resource pack in options.txt");
            return;
        }

        lines.add("resourcePacks:[" + entry + "]");
        write(options, String.join(System.lineSeparator(), lines) + System.lineSeparator());
        PyTrialLog.info("Added the generated resource pack to options.txt");
    }

    private static void write(Path file, String content) throws IOException {
        Files.createDirectories(file.getParent());
        Files.writeString(file, content, StandardCharsets.UTF_8);
    }
}
